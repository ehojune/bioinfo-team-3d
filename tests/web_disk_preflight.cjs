const assert = require('node:assert/strict');
const fs = require('node:fs');
require('../labhq/web/state.js');
const {serviceWarning} = globalThis.LabHQState;
const S = {conn:'live',runnersKnown:true,runners:new Set(['fake'])};
assert.equal(serviceWarning(S),'');
S.runners.clear();
assert.match(serviceWarning(S),/러너 연결 끊김/);
S.conn='offline';
assert.match(serviceWarning(S),/게이트웨이 연결 끊김/);
S.conn='connecting';
assert.match(serviceWarning(S),/게이트웨이 연결 끊김/,'warning persists during retry');
assert.equal(serviceWarning(S,true),'');
S.runnersKnown=false;
assert.equal(serviceWarning(S),'','initial connection is not reported as shutdown');
S.conn='auth';
assert.equal(serviceWarning(S),'','authentication is separate from shutdown');
const twoD = fs.readFileSync(require.resolve('../labhq/web/index.html'),'utf8');
assert.match(twoD,/LabHQState\.serviceWarning\(S, IS_DEMO\)/);
console.log('disk preflight web state: passed');
